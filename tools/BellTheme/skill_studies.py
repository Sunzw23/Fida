renders = []
for s in STUDIES:
    assert len(s['bars']) == 10
    assert all(sum(d for _,d in bar)==4 for bar in s['bars'])
    events = []
    beat = 0
    for bar, notes in enumerate(s['bars']):
        for idx,(note,length) in enumerate(notes):
            if note is not None:
                velocity = [69,65,69,60,70,74,83,66,61,54][bar]
                velocity += (2 if idx==0 else -2 if length<=.5 else 0)
                offset = 0 if idx==0 else .008 / BEAT
                events.append(dict(beat=beat+offset,note=note,duration=length,
                                   gate=min(length*.85,length-.04),velocity=velocity,bar=bar+1))
            beat += length
    midipath = OUT / f'{s["id"]}.mid'
    midi(midipath,events,s['title'],s['key'])
    spec = spec_for(s,events)
    (OUT/f'{s["id"]}.ARR-SPEC.json').write_text(json.dumps(spec,ensure_ascii=False,indent=2),encoding='utf-8')
    bus=engine.empty()
    for e in events:
        engine.strike(bus,e['beat']*BEAT,e['note'],e['velocity']/127*.8,-.07,maximum=6)
    bus=engine.room(bus)
    # Equal-RMS auditions; also constrain true sample peaks. No gain compression.
    peak=max(abs(v) for v in bus)
    rms=math.sqrt(sum(v*v for v in bus)/(len(bus)))
    renders.append((s,bus,peak,rms))

target=min(.055,min(.68*rms/peak for _,_,peak,rms in renders))
reports=[]
for s,bus,peak,rms in renders:
    gain=target/rms
    pcm=array.array('h')
    power=0
    for i in range(engine.N):
        fade=min(1,i/(engine.RATE*.012),(engine.N-1-i)/(engine.RATE*1.5))
        for ch in range(2):
            val=bus[2*i+ch]*gain*fade
            power+=val*val
            pcm.append(round(val*32767))
    path=OUT/f'{s["id"]}.wav'
    with wave.open(str(path),'wb') as w:
        w.setnchannels(2); w.setsampwidth(2); w.setframerate(engine.RATE); w.writeframes(pcm.tobytes())
    report=dict(id=s['id'],title=s['title'],seconds=34,score_seconds=30,
                peak=peak*gain,rms=math.sqrt(power/(engine.N*2)),
                sha256=hashlib.sha256(path.read_bytes()).hexdigest())
    reports.append(report)
    print(json.dumps(report,ensure_ascii=False),flush=True)
(OUT/'manifest.json').write_text(json.dumps(reports,ensure_ascii=False,indent=2),encoding='utf-8')
