def vlq(value):
    result = [value & 127]
    while value >> 7:
        value >>= 7
        result.insert(0, (value & 127) | 128)
    return bytes(result)


def midi(path, events, title, key):
    name = title.encode('utf-8')
    track = b'\0\xff\x03' + vlq(len(name)) + name
    track += b'\0\xff\x51\x03' + round(60_000_000 / BPM).to_bytes(3, 'big')
    track += b'\0\xff\x58\x04\x04\x02\x18\x08'
    sf, minor = {'C major': (0,0), 'D minor': (-1,1), 'F major': (-1,0)}[key]
    track += b'\0\xff\x59\x02' + struct.pack('bB', sf, minor)
    track += b'\0\xc0\x09'  # GM glockenspiel, zero-based program 9
    track += b'\0\xb0\x07\x60\0\xb0\x0a\x3c'
    messages = []
    for e in events:
        tick = round(e['beat'] * PPQ)
        end = tick + round(e['gate'] * PPQ)
        messages += [(tick, 1, bytes([0x90,e['note'],e['velocity']])),
                     (end, 0, bytes([0x80,e['note'],0]))]
    previous = 0
    for tick, order, data in sorted(messages):
        track += vlq(tick - previous) + data
        previous = tick
    track += vlq(40 * PPQ - previous) + b'\xff\x2f\0'
    path.write_bytes(b'MThd' + struct.pack('>IHHH', 6, 0, 1, PPQ)
                     + b'MTrk' + struct.pack('>I', len(track)) + track)


